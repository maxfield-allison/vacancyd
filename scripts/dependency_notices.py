#!/usr/bin/env python3
"""Regenerate or check notices and a deterministic CycloneDX source inventory."""
from __future__ import annotations

import argparse
import hashlib
import gzip
import io
import json
import os
from pathlib import Path
import subprocess
import sys
import tarfile
import tomllib
from urllib.parse import quote

ROOT = Path(__file__).resolve().parent.parent
ABOUT_VERSION = "0.9.2"


def vendored_source() -> tuple[str, bytes, dict]:
    """The bundle exposes the exact modified source, with deterministic bytes."""
    if __package__:
        from .check_vendor import verify
    else:
        from check_vendor import verify
    verify(ROOT)
    record = json.loads((ROOT / 'policy/vendor.json').read_text())
    directory = ROOT / record['directory']
    package = tomllib.loads((directory / 'Cargo.toml').read_text())['package']
    prefix = f"{package['name']}-{package['version']}"
    output = io.BytesIO()
    with gzip.GzipFile(fileobj=output, mode='wb', filename='', mtime=0) as compressed:
        with tarfile.open(fileobj=compressed, mode='w', format=tarfile.PAX_FORMAT) as archive:
            for path in sorted(directory.rglob('*')):
                if not path.is_file():
                    continue
                content = path.read_bytes()
                entry = tarfile.TarInfo(prefix + '/' + path.relative_to(directory).as_posix())
                entry.size, entry.mode, entry.mtime = len(content), 0o644, 0
                archive.addfile(entry, io.BytesIO(content))
    return prefix + '.crate', output.getvalue(), record


def run(*args: str) -> str:
    result = subprocess.run(args, cwd=ROOT, capture_output=True, text=True)
    if result.returncode:
        print(result.stderr, file=sys.stderr)
        result.check_returncode()
    return result.stdout


def identity(package: dict) -> str:
    return f"pkg:cargo/{quote(package['name'], safe='')}@{quote(package['version'], safe='')}"


def render(inventory: dict, metadata: dict, lock: dict, lock_hash: str) -> dict[str, str]:
    """Paths, timestamps and registry cache ordering never enter shipped output."""
    packages = {p["package"]["id"]: p for p in inventory["crates"]}
    covered = set()
    sections = []
    for license in inventory["licenses"]:
        text = license["text"].replace("\r\n", "\n").strip()
        if not text or not license["source_path"]:
            raise ValueError(f"missing upstream license text for {license['id']}; review a pinned clarification")
        users = sorted({f"{u['crate']['name']} {u['crate']['version']}" for u in license["used_by"]})
        covered.update(u["crate"]["id"] for u in license["used_by"])
        sections.append((license["id"], text, users))
    if covered != set(packages):
        raise ValueError("license inventory has missing or unrecognized crate coverage")
    header = [
        "Vacancyd third-party licenses",
        f"Generated by cargo-about {ABOUT_VERSION}; Cargo.lock SHA-256: {lock_hash}",
        "Source dependency inventory for supported targets, including build and development dependencies.",
        "Regenerate with: python3 scripts/dependency_notices.py",
        "Unmodified MPL-2.0 crate sources and the modified Tauri utility source are supplied in THIRD_PARTY_SOURCES.tar.gz.",
        "Its .crate files are gzip-compressed source tar archives; their notices remain intact.",
        "",
    ]
    for entry in sorted(packages.values(), key=lambda p: identity(p["package"])):
        package = entry["package"]
        header.append(f"{package['name']} {package['version']}: {entry['license']}")
        if package.get("source"):
            header.append(f"Source: https://crates.io/api/v1/crates/{package['name']}/{package['version']}/download")
        elif package['name'] == 'tauri-utils':
            header.append('Modified upstream dependency manifest; exact source is in THIRD_PARTY_SOURCES.tar.gz. See docs/dependency-policy.md.')
    for identifier, text, users in sorted(sections):
        header.extend(["", "=" * 72, identifier, "Used by: " + ", ".join(users), "", text])

    checksums = {(p["name"], p["version"]): p.get("checksum") for p in lock["package"]}
    components = []
    for entry in sorted(packages.values(), key=lambda p: identity(p["package"])):
        p = entry["package"]
        ref = identity(p)
        # cargo-about supplies the parsed SPDX expression, including normalized
        # legacy slash alternatives. It remains the only license-policy engine.
        component = {"type": "library", "bom-ref": ref, "name": p["name"],
                     "version": p["version"], "purl": ref,
                     "licenses": [{"expression": entry["license"]}]}
        checksum = checksums.get((p["name"], p["version"]))
        if checksum:
            component["hashes"] = [{"alg": "SHA-256", "content": checksum}]
        elif p['name'] == 'tauri-utils':
            source_name, source_bytes, record = vendored_source()
            component['hashes'] = [{'alg': 'SHA-256', 'content': hashlib.sha256(source_bytes).hexdigest()}]
            component['properties'] = [
                {'name': 'vacancyd:modified', 'value': 'true'},
                {'name': 'vacancyd:source-archive-entry', 'value': source_name},
                {'name': 'vacancyd:upstream-crate-sha256', 'value': record['sha256']},
                {'name': 'vacancyd:upstream-fix', 'value': record['upstream_fix']},
            ]
        components.append(component)
    refs = {key: identity(entry["package"]) for key, entry in packages.items()}
    dependencies = sorted(({
        "ref": refs[node["id"]],
        "dependsOn": sorted({refs[d["pkg"]] for d in node["deps"] if d["pkg"] in refs}),
    } for node in metadata["resolve"]["nodes"] if node["id"] in refs), key=lambda d: d["ref"])
    bom = {"bomFormat": "CycloneDX", "specVersion": "1.6", "version": 1,
           "metadata": {"properties": [
               {"name": "vacancyd:inventory", "value": "source; supported targets; includes build and development dependencies"},
               {"name": "vacancyd:lock-sha256", "value": lock_hash},
               {"name": "vacancyd:license-generator", "value": f"cargo-about {ABOUT_VERSION}"},
           ]}, "components": components, "dependencies": dependencies}
    return {"THIRD_PARTY_LICENSES": "\n".join(header) + "\n",
            "SBOM.cdx.json": json.dumps(bom, indent=2, sort_keys=True, ensure_ascii=False) + "\n"}


def source_archive(inventory: dict, lock: dict) -> bytes:
    """Bundle exact locked upstream sources for all selected MPL obligations."""
    packages = {u["crate"]["id"]: u["crate"] for license in inventory["licenses"]
                if license["id"] == "MPL-2.0" for u in license["used_by"]}
    checksums = {(p["name"], p["version"]): p.get("checksum") for p in lock["package"]}
    cache = Path(os.environ.get("CARGO_HOME", Path.home() / ".cargo")) / "registry/cache"
    output = io.BytesIO()
    with gzip.GzipFile(fileobj=output, mode="wb", filename="", mtime=0) as compressed:
        with tarfile.open(fileobj=compressed, mode="w", format=tarfile.PAX_FORMAT) as archive:
            for package in sorted(packages.values(), key=identity):
                name = f"{package['name']}-{package['version']}.crate"
                expected = checksums.get((package["name"], package["version"]))
                candidates = list(cache.glob(f"*/{name}"))
                contents = next((p.read_bytes() for p in candidates
                                 if hashlib.sha256(p.read_bytes()).hexdigest() == expected), None)
                if not expected or contents is None:
                    raise ValueError(f"missing locked source archive for {name}; cargo fetch --locked first")
                entry = tarfile.TarInfo(name)
                entry.size = len(contents)
                entry.mode = 0o644
                entry.mtime = 0
                archive.addfile(entry, io.BytesIO(contents))
            name, contents, _ = vendored_source()
            entry = tarfile.TarInfo(name)
            entry.size, entry.mode, entry.mtime = len(contents), 0o644, 0
            archive.addfile(entry, io.BytesIO(contents))
    return output.getvalue()


def include_fonts(outputs: dict[str, str]) -> None:
    policy = tomllib.loads((ROOT / "about.toml").read_text())
    bom = json.loads(outputs["SBOM.cdx.json"])
    for font in json.loads((ROOT / "console/font-licenses.json").read_text()):
        if font["license"] not in policy["accepted"]:
            raise ValueError(f"unreviewed font license: {font['license']}")
        for artifact in [*font["files"], font["license_file"]]:
            content = (ROOT / artifact["path"]).read_bytes()
            if hashlib.sha256(content).hexdigest() != artifact["sha256"]:
                raise ValueError(f"font artifact changed: {artifact['path']}; review source and license")
        text = (ROOT / font["license_file"]["path"]).read_text()
        outputs["THIRD_PARTY_LICENSES"] += f"\n{'=' * 72}\n{font['name']} — {font['license']}\n{text}\n"
        ref = f"font:{font['name']}@{font['version']}"
        bom["components"].append({"type": "file", "bom-ref": ref, "name": font["name"],
                                  "version": font["version"], "licenses": [{"license": {"id": font["license"]}}],
                                  "hashes": [{"alg": "SHA-256", "content": p["sha256"]} for p in font["files"]],
                                  "externalReferences": [{"type": "distribution", "url": p["source"]} for p in font["files"]]})
        bom["dependencies"].append({"ref": ref, "dependsOn": []})
        for node in bom["dependencies"]:
            if node["ref"].startswith("pkg:cargo/vacancyd-console@"):
                node["dependsOn"].append(ref)
                node["dependsOn"].sort()
    bom["components"].sort(key=lambda c: c["bom-ref"])
    bom["dependencies"].sort(key=lambda d: d["ref"])
    outputs["SBOM.cdx.json"] = json.dumps(bom, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if committed output differs")
    args = parser.parse_args()
    if run("cargo", "about", "--version").strip() != f"cargo-about {ABOUT_VERSION}":
        raise ValueError(f"install cargo-about {ABOUT_VERSION} with --locked --features cli")
    # Missing packaged licenses use checksum-pinned git clarifications. cargo-about
    # retrieves each from the source commit recorded inside the locked crate;
    # no branch-based or canonical-text fallback is accepted.
    inventory = json.loads(run("cargo", "about", "generate", "--workspace", "--locked",
                               "--all-features", "--fail", "--format", "json"))
    metadata = json.loads(run("cargo", "metadata", "--locked", "--offline", "--all-features",
                              "--format-version", "1"))
    lock_bytes = (ROOT / "Cargo.lock").read_bytes()
    lock = tomllib.loads(lock_bytes.decode())
    outputs = render(inventory, metadata, lock,
                     hashlib.sha256(lock_bytes).hexdigest())
    include_fonts(outputs)
    outputs["THIRD_PARTY_SOURCES.tar.gz"] = source_archive(inventory, lock)
    for name, contents in outputs.items():
        path = ROOT / name
        contents = contents.encode() if isinstance(contents, str) else contents
        if args.check:
            if not path.is_file() or path.read_bytes() != contents:
                raise ValueError(f"{name} is stale; regenerate and review the dependency diff")
        else:
            path.write_bytes(contents)
        print(f"{name}: {'verified' if args.check else 'generated'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
